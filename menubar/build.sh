#!/bin/zsh
# Builds MacBar.app: this directory's host, plus every section it can find.
#
#   ./build.sh                 build into ./MacBar.app
#   ./build.sh --run           build and relaunch it
#   ./build.sh /path/to.app    build somewhere else
#
# Sections live in their own repositories, one per tool, and are found by
# convention under MACBAR_SRC_DIR (default $HOME/Projects):
#
#   <repo>/*Section.swift
#   <repo>/menubar/*Section.swift
#
# A file only counts when it declares a type conforming to BarSection, so an
# unrelated match in some other project is passed over. Whatever is present goes
# in; a repository that is not checked out is simply not a section of this build.
# MACBAR_SECTIONS overrides the search with an explicit list of files, separated
# by colons.
#
# A section is one file, and its name is the name of its type — swiftc requires
# distinct basenames within a module, so `Section.swift` in two repositories
# could not be compiled together.
#
# macOS keeps running the already-launched binary, so the app is stopped first.
# The ad hoc codesign step is required: replacing the executable invalidates the
# existing signature, and an unsigned bundle will not launch on recent macOS.

set -euo pipefail

HERE="${0:A:h}"
SRC_DIR="${MACBAR_SRC_DIR:-$HOME/Projects}"
RUN=0
APP="$HERE/MacBar.app"

for arg in "$@"; do
  case "$arg" in
    --run) RUN=1 ;;
    *)     APP="${arg:A}" ;;
  esac
done

die() { print -u2 -- "\033[31merror:\033[0m $*"; exit 1 }

command -v swiftc >/dev/null || die "swiftc not found — install the Xcode Command Line Tools: xcode-select --install"

# ------------------------------------------------------------------ the sections

# The name of the type a section file declares. One per file: two would make the
# generated list ambiguous, and none means the file is not a section at all.
#
# The address restricts the substitution to a line mentioning BarSection, which
# keeps the pattern itself indifferent to the spacing around the conformance list.
# No \b anywhere: BSD sed does not have it.
section_type() {
  local file="$1"
  sed -nE '/BarSection/ s/^[[:space:]]*(public[[:space:]]+)?(final[[:space:]]+)?class[[:space:]]+([A-Za-z_][A-Za-z0-9_]*).*/\3/p' "$file"
}

typeset -a files chosen types

if [ -n "${MACBAR_SECTIONS:-}" ]; then
  files=(${(s.:.)MACBAR_SECTIONS})
  for f in $files; do
    [ -f "$f" ] || die "MACBAR_SECTIONS names a file that is not there: $f"
  done
else
  # Byte order, so the sections come out in the same order on every machine, and
  # (N) so a pattern that matches nothing disappears instead of erroring.
  local -x LC_COLLATE=C
  files=($SRC_DIR/*/*Section.swift(N) $SRC_DIR/*/menubar/*Section.swift(N))
fi

for f in $files; do
  typeset -a found
  found=(${(f)"$(section_type "$f")"})
  found=(${found:#})
  case ${#found} in
    0) continue ;;
    1) chosen+=("$f"); types+=("${found[1]}") ;;
    *) die "$f declares more than one BarSection type (${found[*]}) — a section file should declare exactly one" ;;
  esac
done

[ ${#chosen} -gt 0 ] || die "no sections found under $SRC_DIR — clone at least one section repository, or set MACBAR_SECTIONS"

# Two checkouts of the same section would collide in the generated list.
if [ ${#${(u)types}} -ne ${#types} ]; then
  die "two section files declare the same type (${types[*]}) — is a repository checked out twice under $SRC_DIR?"
fi

print -- "Sections:"
for i in {1..${#chosen}}; do
  print -- "  ${types[$i]}  ←  ${chosen[$i]}"
done

# ----------------------------------------------------------------- generated list

BUILD="$HERE/.build"
mkdir -p "$BUILD"
GENERATED="$BUILD/Sections.swift"

{
  print -- "// Generated by build.sh — not part of the repository."
  print -- "//"
  print -- "// Whichever sections were found at build time, in the order they are shown."
  print -- ""
  print -- "let sections: [BarSection] = ["
  for t in $types; do print -- "    $t(),"; done
  print -- "]"
} > "$GENERATED"

# ------------------------------------------------------------------------- build

pkill -x MacBar 2>/dev/null || true

mkdir -p "$APP/Contents/MacOS"
cp "$HERE/Info.plist" "$APP/Contents/Info.plist"

swiftc -O \
  "$HERE/Support.swift" \
  "$HERE/Controller.swift" \
  "$HERE/Host.swift" \
  $chosen \
  "$GENERATED" \
  "$HERE/main.swift" \
  -o "$APP/Contents/MacOS/MacBar"

codesign --force --sign - "$APP"

print -- "Built $APP"

if [ "$RUN" = 1 ]; then
  open "$APP"
  print -- "Launched — look for the gauge in the menu bar"
fi
